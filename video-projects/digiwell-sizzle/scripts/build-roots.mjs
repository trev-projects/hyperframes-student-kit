#!/usr/bin/env node
// Writes index.html (16:9, services page) and build/vertical/ (9:16, socials)
// from ONE scene list, so the two formats can never drift apart.
// HyperFrames allows one root composition per project, so the vertical cut is
// generated as a sibling project: a fresh copy of compositions/ + assets/ with
// a portrait root. Never edit build/ by hand; edit here and in compositions/.
// Scenes overlap by 0.4s on alternating tracks: each incoming scene runs its
// own transition over the outgoing one.
//
// Usage (from the project folder): node scripts/build-roots.mjs

import { writeFileSync, mkdirSync, rmSync, cpSync, readFileSync, readdirSync } from 'node:fs';

const SCENES = [
  { id: 'z1-hook',    start: 0.0,  dur: 5.8 },
  { id: 'z2-thesis',  start: 5.4,  dur: 4.2 },
  { id: 'z3-services', start: 9.2,  dur: 6.4 },
  { id: 'z4-how',     start: 15.2, dur: 10.4 },
  { id: 'z5-commit',  start: 25.2, dur: 3.6 },
  { id: 'z6-cta',     start: 28.4, dur: 5.6 }
];
const TOTAL = 34;

const FORMATS = [
  { file: 'index.html', w: 1920, h: 1080, label: '16:9' },
  { file: 'build/vertical/index.html', w: 1080, h: 1920, label: '9:16', dir: 'build/vertical' }
];

for (const f of FORMATS) {
  if (f.dir) {
    rmSync(f.dir, { recursive: true, force: true });
    mkdirSync(f.dir, { recursive: true });
    cpSync('compositions', `${f.dir}/compositions`, { recursive: true });
    // Scenes size themselves from their OWN template dimensions, not the host
    // clip's, so stamp the portrait size into each copied scene.
    for (const name of readdirSync(`${f.dir}/compositions`)) {
      const fp = `${f.dir}/compositions/${name}`;
      writeFileSync(fp, readFileSync(fp, 'utf8')
        .replace(/data-width="1920" data-height="1080"/g, `data-width="${f.w}" data-height="${f.h}"`));
    }
    cpSync('assets', `${f.dir}/assets`, { recursive: true });
    cpSync('hyperframes.json', `${f.dir}/hyperframes.json`);
    const meta = JSON.parse(readFileSync('meta.json', 'utf8'));
    writeFileSync(`${f.dir}/meta.json`, JSON.stringify({ ...meta, id: meta.id + '-vertical', name: meta.name + ' (9:16)', width: f.w, height: f.h }, null, 2) + '\n');
  }
  const clips = SCENES.map((s, i) => `      <div id="${s.id}" class="scene-layer" data-composition-id="${s.id}"
        data-composition-src="compositions/${s.id}.html"
        data-start="${s.start}" data-duration="${s.dur}" data-track-index="${i % 2}"
        data-width="${f.w}" data-height="${f.h}"></div>`).join('\n\n');

  writeFileSync(f.file, `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${f.w}, height=${f.h}" />
    <title>Digiwell Marketing — How we work (${f.label})</title>
    <!-- GENERATED by scripts/build-roots.mjs. Edit that, not this file. -->
    <script src="assets/gsap.min.js"></script>
    <link rel="preload" href="assets/fonts/Sora.woff2" as="font" type="font/woff2" crossorigin />
    <link rel="preload" href="assets/fonts/Manrope.woff2" as="font" type="font/woff2" crossorigin />
    <link rel="preload" href="assets/fonts/JetBrainsMono.woff2" as="font" type="font/woff2" crossorigin />
    <link rel="stylesheet" href="assets/sz.css" />
    <style>
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: ${f.w}px; height: ${f.h}px; overflow: hidden; background: #F1ECE3; }
      .scene-layer { position: absolute; top: 0; left: 0; width: ${f.w}px; height: ${f.h}px; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="digiwell-sizzle"
      data-start="0" data-duration="${TOTAL}" data-width="${f.w}" data-height="${f.h}">
${clips}

      <audio id="sfx" data-start="0" data-duration="${TOTAL}" data-track-index="21"
        data-volume="1" src="assets/sfx.wav"></audio>
    </div>
    <script>
      window.__timelines = window.__timelines || {};
      const tl = gsap.timeline({ paused: true });
      tl.to({}, { duration: ${TOTAL} }, 0);
      window.__timelines["digiwell-sizzle"] = tl;
    </script>
  </body>
</html>
`);
  console.log(`${f.file}: ${f.label}, ${SCENES.length} scenes, ${TOTAL}s`);
}
